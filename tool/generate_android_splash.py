#!/usr/bin/env python3
"""Reapply Android launch resources, preserving the approved 946 x 2048 image.

Run from any directory: python3 tool/generate_android_splash.py
After flutter_native_splash:create, rerun this script: the package cannot express
aspect-fit bitmap sizing or a transparent vector for Android 12's system icon.
This script never changes iOS, the official SVGs, launcher icons, or app code.
"""

import argparse
import shutil
import struct
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path


COLOR = "#123E67"
IMAGE_WIDTH, IMAGE_HEIGHT = 946, 2048
# (minimum available width, minimum available height, image width in dp).
# Android chooses the best matching qualifier; every size fits its own minimum.
# The reduced default also accommodates small multi-window/landscape windows.
SIZES = [
    (0, 0, 96),
    (0, 320, 128),
    (0, 480, 200),
    (320, 600, 260),
    (360, 640, 280),
    (360, 720, 310),
    (393, 800, 350),
]


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def transparent_png(size=1152):
    def chunk(kind, data):
        return (
            struct.pack(">I", len(data))
            + kind
            + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
        )

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">2I5B", size, size, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress((b"\x00" * (size * 4 + 1)) * size, 9))
        + chunk(b"IEND", b"")
    )


def set_item(style, name, value):
    item = next((item for item in style.findall("item") if item.get("name") == name), None)
    if item is None:
        item = ET.SubElement(style, "item", {"name": name})
    item.text = value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--source", type=Path, help="Initial approved PNG; copied unchanged")
    args = parser.parse_args()
    root = args.root.resolve()
    assets = root / "assets/branding/institutional"
    image = assets / "native_launch.png"
    if args.source:
        assets.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(args.source, image)
    data = image.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n" or struct.unpack(">II", data[16:24]) != (IMAGE_WIDTH, IMAGE_HEIGHT):
        raise ValueError("Expected the approved 946 x 2048 PNG; image was not changed")
    transparent = assets / "android_splash_transparent.png"
    transparent.write_bytes(transparent_png())
    res = root / "android/app/src/main/res"
    destination = res / "drawable-nodpi/institutional_launch.png"
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(image, destination)

    for min_width, min_height, width in SIZES:
        qualifiers = (f"-w{min_width}dp" if min_width else "") + (f"-h{min_height}dp" if min_height else "")
        height = width * IMAGE_HEIGHT / IMAGE_WIDTH
        if min_width and width > min_width:
            raise ValueError("Launch width exceeds qualifier")
        if min_height and height > min_height:
            raise ValueError("Launch height exceeds qualifier")
        color = f'    <color name="institutional_launch_background">{COLOR}</color>\n' if not qualifiers else ""
        write(res / f"values{qualifiers}/institutional_launch.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_splash.py. Image ratio: 946:2048. -->
<resources>
{color}    <dimen name="institutional_launch_width">{width:.6f}dp</dimen>
    <dimen name="institutional_launch_height">{height:.6f}dp</dimen>
</resources>
''')

    background = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_splash.py. Android 8-11 only.
     Keep the complete approved composition, with institutional letterboxing.
     Both item dimensions preserve 946:2048; fill never changes its aspect ratio. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/institutional_launch_background" />
    <item android:width="@dimen/institutional_launch_width"
        android:height="@dimen/institutional_launch_height"
        android:gravity="center">
        <bitmap android:src="@drawable/institutional_launch"
            android:gravity="fill" android:filter="true" />
    </item>
</layer-list>
'''
    for folder in ("drawable", "drawable-v21", "drawable-night", "drawable-night-v21"):
        write(res / folder / "launch_background.xml", background)

    write(res / "drawable/institutional_launch_icon.xml", '''<?xml version="1.0" encoding="utf-8"?>
<!-- Android 12+ requires the system icon slot. Explicit transparency avoids
     falling back to the old launcher emblem; Flutter draws the full design. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="288dp" android:height="288dp"
    android:viewportWidth="288" android:viewportHeight="288">
    <path android:fillColor="#00000000" android:pathData="M0,0h288v288h-288z" />
</vector>
''')

    for folder in ("values", "values-night", "values-v31", "values-night-v31"):
        path = res / folder / "styles.xml"
        tree = ET.parse(path, parser=ET.XMLParser(target=ET.TreeBuilder(insert_comments=True)))
        launch = tree.find("./style[@name='LaunchTheme']")
        normal = tree.find("./style[@name='NormalTheme']")
        if launch is None or normal is None:
            raise ValueError(f"Expected LaunchTheme and NormalTheme in {path}")
        set_item(normal, "android:windowBackground", "@color/institutional_launch_background")
        set_item(launch, "android:windowFullscreen", "false")
        set_item(launch, "android:windowDrawsSystemBarBackgrounds", "true")
        set_item(launch, "android:statusBarColor", "@color/institutional_launch_background")
        set_item(launch, "android:navigationBarColor", "@color/institutional_launch_background")
        set_item(launch, "android:windowLightStatusBar", "false")
        set_item(launch, "android:windowLightNavigationBar", "false")
        set_item(launch, "android:windowLayoutInDisplayCutoutMode", "default")
        if "v31" in folder:
            set_item(launch, "android:windowBackground", "@color/institutional_launch_background")
            set_item(launch, "android:windowSplashScreenBackground", "@color/institutional_launch_background")
            set_item(launch, "android:windowSplashScreenAnimatedIcon", "@drawable/institutional_launch_icon")
        ET.indent(tree, space="    ")
        write(path, '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(tree.getroot(), encoding="unicode") + "\n")

    write(root / "flutter_native_splash.yaml", f'''# Android resource regeneration:
#   dart run flutter_native_splash:create
#   python3 tool/generate_android_splash.py
# The final step restores proportional Android <=11 composition and the
# Android 12+ transparent vector. iOS is maintained in LaunchScreen.storyboard.
flutter_native_splash:
  color: "{COLOR}"
  color_dark: "{COLOR}"
  android: true
  ios: false
  web: false
  fullscreen: false
  android_12:
    color: "{COLOR}"
    color_dark: "{COLOR}"
    image: assets/branding/institutional/android_splash_transparent.png
    image_dark: assets/branding/institutional/android_splash_transparent.png
''')
    print("Android launch resources generated; official artwork and iOS unchanged.")


if __name__ == "__main__":
    main()
